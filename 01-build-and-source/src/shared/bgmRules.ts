/**
 * BGM의 순수 규칙 — 게인 상한·페이드·파일명.
 *
 * 설계 문서: specs/2026-07-27-ux/01-art-direction.md §7 (오디오)
 *
 * `audio.ts`처럼 WebAudio를 쓰는 코드는 node 테스트에서 로드할 수 없으므로
 * (`audioRules.ts`와 같은 관례) 숫자만 여기 둔다.
 *
 * ## 스펙이 "BGM은 넣지 않는다"였다 — 무엇이 바뀌었나
 *
 * §01-7과 §09가 둘 다 "용량이 크고 **120초 대전**에서 루프가 어색하다"고 적었다.
 * 그 논거는 **대전에서는 아직 맞다** — 그래서 BGM은 대전에 넣지 않는다.
 * 뒤집힌 것은 전제다: 하강 모드가 생기면서 세션 길이가 120초에서 **4시간**이
 * 됐다(방치형 페이싱 실측 240분 = 518층). 120초에 한 바퀴도 못 도는 곡이
 * 어색한 것과, 4시간을 효과음만으로 채우는 것은 다른 문제다.
 *
 * 용량 논거는 실측으로 답한다: 모노 56kbps로 **1.0MB**다(`fetch_bgm.sh`의
 * `MAX_BYTES`가 지킨다). 기존 에셋 8.6MB에 대해 12%이고, **부팅을 막지 않는다**
 * — 하강에 들어갈 때 받는다(`audio.startBgm`).
 *
 * ## 게인은 **양쪽**에서 조인다 — 한쪽만 풀었다가 안 들렸다
 *
 * > **정정 (2026-08-07, 실제로 안 들려서).** 처음 이 파일은 상한만 유도하고
 * > 0.22를 골랐다. 배포본에서 유저가 "BGM이 안 들린다"고 했고, 재보니 실효
 * > 라우드니스가 **−35.4 LUFS**였다 — 휴대폰 스피커의 가청 바닥 아래다.
 * > 그래프·파일·배선은 전부 정상이었고(프로덕션 프로브로 확인: 소스 1개,
 * > `source → bgmGain → master → destination`, 게인 0.22 그대로) **틀린 것은
 * > 상수 하나**였다. 원인은 유도가 **편측**이었다는 것이다: "효과음을 덮지
 * > 마라"만 풀고 "들려야 한다"는 부등식을 아예 쓰지 않았다. 하한 없는 상한은
 * > 0으로도 만족되므로, 그 조건은 무음을 통과시킨다.
 *
 * 그래서 지금은 두 부등식을 같이 푼다.
 *
 * **① 상한 — 신호가 묻히면 안 된다.** BGM이 효과음을 덮으면 그 효과음은 신호가
 * 아니게 된다(층 돌파·보스 등장을 소리로 알 수 없다).
 *
 * **② 하한 — 들려야 넣은 값을 한다.** 1MB를 받아 4시간 돌리면서 안 들리면
 * 넣지 않은 것과 같다. 베드 라우드니스 **≥ −30 LUFS**로 잡았다.
 *
 * ## 효과음을 두 부류로 나눈 것이 핵심이었다
 *
 * 처음 상한을 `hit_0`이 정하게 뒀는데 그게 틀렸다. `hit_0`은 **매 타격마다 깔리는
 * 질감**이고, 부분적으로 음악에 섞여도 잃는 정보가 없다. 반면 놓치면 안 되는
 * 것은 **사건을 알리는 소리**다.
 *
 * | 부류 | 효과음 | 요구 |
 * |------|--------|------|
 * | **신호** | `cooldown_ready` `gauge_danger` `skill_cast` `enemy_death` `interference` | 베드보다 **≥6dB** |
 * | 질감 | `hit_0` `ui_tap` | 요구 없음 (아래 온셋 표를 보라) |
 *
 * 400ms 라우드니스 창에서 신호 여유가 6dB을 지키는 최대 게인이 **0.46**이고,
 * 베드가 −30 LUFS를 넘는 최소 게인이 **0.43**이다. 창이 4스텝밖에 안 되므로
 * **중간(0.44)** 을 쓴다 — 여느 때처럼 "상한에서 20% 내려" 잡을 수 없다.
 * 두 경계가 거의 맞닿았다는 것 자체가 기록해 둘 값이다: 곡을 바꾸면 겹치는
 * 구간이 사라질 수 있고, 그때는 게인이 아니라 **곡이나 믹스**를 바꿔야 한다.
 *
 * ## 질감이 죽지 않는지는 다른 창으로 물었다
 *
 * 400ms 적분에서 `hit_0` 여유가 0.4dB까지 내려가는데, 그 창은 **과도음에 맞는
 * 자가 아니다** — 타격음은 50ms 안에 끝나므로 400ms에 녹여 재면 실제보다
 * 비관적으로 나온다. 온셋 창(50ms)으로 다시 재면 게인 0.44에서:
 *
 * | 효과음 | 온셋 여유 |
 * |--------|----------|
 * | `skill_cast` | +25.3dB |
 * | `cooldown_ready` | +19.0dB |
 * | `gauge_danger` | +16.1dB |
 * | `enemy_death` | +15.1dB |
 * | `interference` | +14.4dB |
 * | `hit_0` | **+12.7dB** |
 * | `ui_tap` | +3.7dB |
 *
 * 타격 피드백이 최우선이라는 스펙 §09-2와 충돌하지 않는다. `ui_tap`만 낮은데
 * 그건 원본이 −31dBFS로 구워진 것이라 음악과 무관한 별개 문제다.
 *
 * 클리핑도 확인했다: BGM 피크와 가장 센 효과음이 겹쳐도 합이 −2.2dBFS다.
 *
 * ## 게인은 **곡마다 다시 유도한다** (2026-08-08, 타이틀 곡 추가)
 *
 * 위 유도가 곡 하나(`dive_loop`)에 매인 것이었다. 타이틀 곡(`title_loop`)은
 * 2.0 LUFS 크게 구워져 있어서 **같은 게인이 다른 크기로 들린다** — dive의 0.44를
 * 그대로 쓰면 베드가 마스킹 한계를 **2.27dB 넘는다**(층 돌파·보스 신호가 음악에
 * 묻힌다). 슬러그만 바꾸고 게인을 복사하는 것이 가장 자연스러운 실수이므로
 * 테스트가 그것을 명시적으로 한 번 더 묻는다.
 *
 * 그런데 상한을 곡별로 **다시 재지는 않는다.** 마스킹 한계는 효과음의 성질이고
 * (`interference` 파일이 안 바뀌었다) 음악은 그 레벨에 닿는지만 묻는다. 그래서
 * 한계를 **베드 레벨**로 옮겨 두고(`BGM_MASK_BED_DBFS`) 게인은 곡의 실측에서 푼다.
 *
 * | | dive | title |
 * |---|---|---|
 * | 소스 LUFS (인코딩 후 실측) | −20.3 | −18.3 |
 * | 베드@게인1 (400ms 창 중앙값) | −19.27 dBFS | −16.61 dBFS |
 * | 하한 (베드 ≥ −30 LUFS) | 0.4092 | 0.3250 |
 * | 상한 (베드 ≤ 마스킹 한계) | 0.4600 | 0.3387 |
 * | 쓰는 값 | **0.44** | **0.33** |
 *
 * 표는 `tools/measure_bgm_gain.py`가 만든다 — 곡을 바꾸면 그것을 돌린다.
 * 숫자를 옮겨 적는 자리가 아니다.
 *
 * ## 두 경계는 **서로 다른 자로** 재진다 — 한 자로 섞으면 상한이 헐거워진다
 *
 * 하한은 "들려야 한다"이고 사람이 듣는 크기는 통합 라우드니스이므로 **LUFS**로
 * 잰다. 상한은 "효과음이 묻히면 안 된다"이고 마스킹은 겹치는 순간의 문제이므로
 * **400ms 창 dBFS**로 잰다. 그래서 트랙이 `sourceLufs`와 `bedUnityDbfs`를 둘 다
 * 들고 있다.
 *
 * 한 자로 섞으면(상한도 `sourceLufs`에서 풀면) dive 상한이 0.518로 나온다 —
 * 실측 경계 0.460보다 **1.2dB 헐거운** 게이트이고, 그 상태에서도 "게인이 상한
 * 아래" 검사는 전부 통과한다. 상한을 느슨하게 만드는 변경이 조용한 것이
 * 정확히 0.22 사건의 형태다.
 *
 * **겹치는 구간이 없을 수 있다.** 위 머리말이 "곡을 바꾸면 겹치는 구간이 사라질
 * 수 있다"고 예고했고, 후보였던 `Ossuary 6 - Air`에서 실제로 일어났다 — 그 곡은
 * 게인으로 풀 수 없어서 탈락했다. 테스트가 그 부등식을 트랙마다 묻는다.
 */

/** 어느 화면의 음악인가. 트랙을 늘리려면 여기에 더한다 */
export type BgmTrack = "title" | "dive";

/**
 * 마스킹 한계 — 베드(음악만)의 400ms 창 중앙값이 이 dBFS를 넘으면 신호 효과음이
 * 6dB을 못 남긴다.
 *
 * **유래**: dive의 상한 0.46(위 머리말이 유도하고 **귀로 검증까지 지난** 값)에서
 * 베드를 재면 −27.95 dBFS다. 즉 이 숫자는 새 실측이 아니라 **기존 유도를 게인에서
 * 레벨로 옮겨 적은 것**이다 — 그래야 곡이 바뀔 때 효과음을 다시 재지 않는다.
 * `tools/measure_bgm_gain.py`가 그 이식을 되돌려 확인한다(한계 레벨 → dive 상한
 * 0.4600).
 *
 * 6dB 유도 자체를 다시 돌리지 않는 이유는 그 스크립트 머리말에 있다: 원래 쓰인
 * 창·가중이 코드에 안 남아 재현이 안 되고, 소박하게 다시 풀면 dive 상한이 0.204로
 * 나와 **하한 0.409보다 낮다**(겹치는 구간이 없다는 뜻인데, 그 방향으로 배포해서
 * 받은 보고가 "안 들린다"였다).
 */
export const BGM_MASK_BED_DBFS = -27.95;

/**
 * 베드(음악만)가 지켜야 하는 최소 라우드니스.
 *
 * −30 LUFS를 휴대폰 스피커의 실질 가청 바닥으로 잡았다. 문제였던 0.22는
 * −35.4 LUFS였다.
 */
export const BGM_BED_MIN_LUFS = -30;

/** 마스터 볼륨 — `audio.ts`의 `MASTER_VOLUME`과 같아야 한다 */
const MASTER = 0.8;

/**
 * 게인 `g`로 재생할 때 음악만의 라우드니스(LUFS). **하한을 푸는 자다.**
 *
 * 마스터(`MASTER_VOLUME` 0.8)까지 포함한다 — 플레이어가 듣는 것이 그것이다.
 * 게인은 선형 배율이므로 라우드니스는 `20·log10`만큼 옮겨진다.
 *
 * @param sourceLufs 그 트랙 파일의 통합 라우드니스 — **트랙마다 다르다.**
 *   인자로 받는 것이 이 회차의 변경이다: 상수로 두면 트랙을 늘린 날 새 곡이
 *   옛 곡의 라우드니스로 검증된다.
 *
 * 가드가 막는 것은 **0이 아니라 음수다.** `Math.log10(0)`은 이미 `-Infinity`라
 * 0은 가드 없이도 맞게 나오지만, 음수는 `NaN`이 되고 `NaN < 목표`가 거짓이라
 * **가청 검사가 조용히 통과한다.** (돌연변이로 확인했다: 가드를 지웠을 때 0
 * 케이스만으로는 아무것도 안 울렸다.)
 */
export function bedLufs(
  gain: number,
  sourceLufs: number,
  master = MASTER,
): number {
  if (gain <= 0 || master <= 0) return Number.NEGATIVE_INFINITY;
  return sourceLufs + 20 * Math.log10(gain * master);
}

/**
 * 게인 `g`로 재생할 때 베드의 400ms 창 레벨(dBFS). **상한을 푸는 자다.**
 *
 * `bedLufs`와 나란히 있는 것이 의도다 — 두 경계가 서로 다른 척도로 재진다는
 * 사실이 함수 두 개로 드러나야, 다음 사람이 한쪽 자로 양쪽을 풀지 않는다.
 *
 * @param bedUnityDbfs 게인 1에서의 베드 레벨. `tools/measure_bgm_gain.py` 실측.
 */
export function bedDbfs(
  gain: number,
  bedUnityDbfs: number,
  master = MASTER,
): number {
  if (gain <= 0 || master <= 0) return Number.NEGATIVE_INFINITY;
  return bedUnityDbfs + 20 * Math.log10(gain * master);
}

/**
 * 이 라우드니스의 곡에서 **가장 작게 쓸 수 있는** 게인 — 베드가
 * `BGM_BED_MIN_LUFS`를 넘는 경계.
 *
 * 숫자를 상수로 박지 않고 함수로 두는 이유: 상수는 곡을 바꾼 날 옛 곡의 하한을
 * 새 곡에 적용하고, 그 상태가 **테스트를 전부 통과한다**(0.22 사건의 형태).
 */
export function bgmGainFloor(sourceLufs: number, master = MASTER): number {
  return 10 ** ((BGM_BED_MIN_LUFS - sourceLufs) / 20) / master;
}

/**
 * 이 곡에서 **가장 크게 쓸 수 있는** 게인 — 베드가 `BGM_MASK_BED_DBFS`에 닿는
 * 경계. 이 위로 올리면 신호 효과음이 6dB을 못 남긴다.
 *
 * **`sourceLufs`가 아니라 `bedUnityDbfs`를 받는다.** 라우드니스로 풀면 dive에서
 * 0.518이 나와 실측 경계 0.460보다 헐거워지고, 그 헐거움은 어떤 검사도 안 울린다.
 */
export function bgmGainCeiling(bedUnityDbfs: number, master = MASTER): number {
  return 10 ** ((BGM_MASK_BED_DBFS - bedUnityDbfs) / 20) / master;
}

/**
 * 트랙 표.
 *
 * `gain`을 함수로 계산하지 않고 **적어 두는** 이유: 겹치는 구간의 어디를 쓰는지는
 * 판단이다(중간에 가깝게 쓴다 — 상한에서 20% 내리면 하한을 뚫는다). 테스트가 그
 * 값이 자기 구간 안인지를 묻고, 유도는 위 두 함수가 갖는다.
 *
 * `sourceLufs`·`bedUnityDbfs`는 **인코딩 후** 파일의 실측이다(원본 mp3가 아니다)
 * — 56k ogg 인코딩이 라우드니스를 옮긴다(dive 원본 −17.3 → 파일 −20.3).
 */
export const BGM_TRACKS: Readonly<
  Record<
    BgmTrack,
    {
      /** `public/assets/bgm/<slug>.{ogg,m4a}` — `bgm.json`의 슬러그와 같아야 한다 */
      readonly slug: string;
      readonly gain: number;
      /** `ffmpeg -af ebur128` 실측 (인코딩 후). 하한을 푼다 */
      readonly sourceLufs: number;
      /** 게인 1에서의 400ms 창 중앙값(dBFS). 상한을 푼다 */
      readonly bedUnityDbfs: number;
      readonly loopS: number;
      /** 실측 박(초). 프레이즈 = 박 × 4 × 2 */
      readonly beatS: number;
    }
  >
> = {
  // 타이틀·선택 화면. Crypto, 30마디. dive보다 밝고 성부가 적다 —
  // 톤이 달라야 분리한 값을 한다(설계 §4-4)
  title: {
    slug: "title_loop",
    gain: 0.33,
    sourceLufs: -18.3,
    bedUnityDbfs: -16.61,
    loopS: 89.16,
    beatS: 0.743,
  },
  // 하강. Oppressive Gloom, 40마디. 0.44는 귀로 검증된 값이다(0.22 사건의 답)
  dive: {
    slug: "dive_loop",
    gain: 0.44,
    sourceLufs: -20.3,
    bedUnityDbfs: -19.27,
    loopS: 163.2,
    beatS: 1.02,
  },
} as const;

/**
 * 페이드 인/아웃 시간(ms).
 *
 * **0으로 시작하면 "툭" 소리가 난다** — 루프 앞머리는 크로스페이드로 이미
 * 소리가 실려 있어서(무음에서 시작하지 않는다) 게인을 즉시 올리면 그 진폭이
 * 그대로 클릭이 된다.
 *
 * 나가는 쪽이 **더 짧다.** 이제 그것이 실제 경로가 된다: 하강을 나가면 타이틀
 * 음악이 들어오므로, 나가는 쪽이 길면 두 곡이 겹친다. 겹치면 두 곡의 조성이
 * 부딪히는데 **그건 진폭 지표에 안 걸린다** — 그래서 전환은 크로스페이드가
 * 아니라 순차다(`audio.startBgm`).
 */
export const BGM_FADE_IN_MS = 1200;
export const BGM_FADE_OUT_MS = 600;

/**
 * 유저 설정에서 BGM이 나는가.
 *
 * 무음(0)에서 **버퍼 소스를 아예 만들지 않기 위해** 따로 묻는다. 게인 0으로도
 * 안 들리지만, 4시간 동안 디코드된 1MB 버퍼를 루프로 돌리는 것은 순수한
 * 낭비다(`playSfx`가 같은 이유로 무음일 때 노드를 안 만든다).
 */
export function bgmAudible(volume: number): boolean {
  return Number.isFinite(volume) && volume > 0;
}
