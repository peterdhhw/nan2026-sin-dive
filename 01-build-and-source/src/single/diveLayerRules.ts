/**
 * 싱글 씬이 **최상단 레이어(`layers.fx`) 안에서** 무엇을 어느 순서로 쌓는가.
 *
 * ## 왜 규칙으로 올렸나 (2026-08-07)
 *
 * 순서가 `session.ts`의 **주석**에만 있었고("z순서: … → fx·공지·모달(fx)"),
 * 그래서 아무도 물어볼 수 없었다. 실제로 캡처에서 결함이 나왔다: 강화 시트가
 * `layers.skillBar`에 있고 전투 이펙트가 `layers.fx`에 있어서, **시트를 열어도
 * 이펙트가 시트 위에 그려졌다.** 42층에서 `스킬 위력 Lv.30`의 레벨 숫자와
 * `×10.06`이 별 파편에 완전히 묻혀 읽을 수 없었다(1:1 캡처 확인).
 *
 * 조용한 종류의 결함이다 — 시트는 하강을 멈추지 않으므로(`paused`가 아니다)
 * 뒤에서 전투가 계속 돌고, 이펙트는 몇 백 ms만 떠 있다. 캡처 한 장이 이펙트가
 * 없는 순간에 찍히면 멀쩡해 보인다. 게다가 우리 소개서 §3-5는 심사자에게
 * **5번에서 이 시트를 열라고** 안내한다 — 하강 중에 열게 되어 있는 화면이다.
 *
 * ## 순서가 세 부등식으로 갇혀 있다
 *
 * 1. **시트는 이펙트보다 위다.** 아래면 위 결함이 그대로다. 위로 올리면
 *    이펙트가 시트의 딤(`scrim`) **아래로** 들어가므로 같이 어두워진다 —
 *    "뒤에서 전투가 계속 돈다"는 사실은 남고 글자만 읽힌다.
 * 2. **토스트는 시트보다 위다.** 카드 뽑기가 시트 **안에** 있고, 그 결과를
 *    말하는 것이 토스트다(`drawOneCard` → `toast.show`). 아래면 방금 누른
 *    버튼의 결과가 자기가 띄운 패널에 가려진다.
 * 3. **스토리 모달은 시트·토스트보다 위다.** 심연의 선택은 판을 멈추고(`paused`),
 *    시트가 열린 채로도 뜬다(시트는 `paused`가 아니다).
 * 4. **층 돌파 쇼케이스가 가장 위다 — 스토리 모달보다도 위다.** 이유가 뒤집혀
 *    보이므로 적어 둔다: 쇼케이스는 **스스로 걷히고**(2.6초) 스토리 모달은
 *    **입력을 기다린다.** 그래서 순서를 뒤집으면 두 결함이 동시에 생긴다.
 *    (a) 50층은 미니보스 층이면서 심연의 선택 층이다(`CHOICE_EVERY` 50 =
 *    `MINIBOSS_EVERY` 10의 배수) — 즉 둘이 **실제로 같은 프레임에 뜬다.**
 *    쇼케이스가 아래면 방금 신고받은 그 축하가 첫 등장 프레임부터 모달에
 *    가려진다. (b) 쇼케이스는 딤으로 **탭을 삼킨다** — 위에 있으면 화면에
 *    안 보이는 `수용한다`(타락도 +10, 엔딩을 가르는 선택)가 눌리는 일이
 *    없다. 아래면 축하 위에 뜬 버튼을 눌러 선택이 끝나 버린다.
 *    쇼케이스가 걷히면 그 아래에 모달이 그대로 남아 있다(각자 다른 정지
 *    플래그를 쥔다 — `session.ts`의 `showcaseLive`).
 *
 * 배너는 시트보다 위지만 그건 기하로도 안 겹친다 — `SHEET_Y`가
 * `BANNER_BOTTOM_Y`에서 유도된다(`upgradePanelRules.SHEET_H` 주석).
 * 위에 두는 것은 그 유도가 깨지는 날의 안전망이다.
 *
 * Pixi를 import하지 않는다 — node 테스트에서 그대로 로드된다.
 */

/**
 * `layers.fx`의 자식 순서 — **앞이 아래**(먼저 그려진다).
 *
 * 씬은 이 배열을 돌면서 붙인다(`session.ts`). 배열을 안 돌고 손으로 붙이면
 * 이 파일은 다시 주석이 된다.
 */
export const DIVE_FX_STACK = [
  /** 전투 이펙트 — 타격·처치·버프 */
  "effects",
  /** 강화 시트 + 딤 */
  "upgradeSheet",
  /** 층 돌파 배너 */
  "banner",
  /** 획득·안내 토스트 */
  "toast",
  /** 튜토리얼 손가락 */
  "hintFinger",
  /** 프롤로그·심연의 선택·엔딩 */
  "story",
  /** 층 돌파 쇼케이스 (삽화 + 층수 + 획득 카드) — 스스로 걷히므로 맨 위다 */
  "showcase",
] as const;

export type DiveFxLayerName = (typeof DIVE_FX_STACK)[number];

/**
 * 쌓임 순서에서의 자리. 없는 이름은 `-1`이다 — 호출부가 조용히 0으로 읽고
 * 맨 아래에 붙이면, 이름을 잘못 적은 것이 "가장 뒤에 그려짐"으로 나타난다.
 */
export function fxStackIndex(name: string): number {
  return (DIVE_FX_STACK as readonly string[]).indexOf(name);
}

/** `a`가 `b`보다 위에 그려지는가 */
export function drawsAbove(a: DiveFxLayerName, b: DiveFxLayerName): boolean {
  return fxStackIndex(a) > fxStackIndex(b);
}
